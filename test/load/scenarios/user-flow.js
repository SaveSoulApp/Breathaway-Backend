import http from 'k6/http';
import { check, group, sleep } from 'k6';

// Register expected HTTP response codes across diverse lifecycle actions
// 200: OK (GET / PATCH / pre-flight)
// 201: Created (POST /likes, POST /one-time-passwords/*)
// 202: Accepted (Async actions)
// 404: Not Found (GET /subscriptions/me when user has no active subscription)
// 409: Conflict (Duplicate like or already matched during pre-flight checks)
http.setResponseCallback(http.expectedStatuses(200, 201, 202, 404, 409));

import { getBaseUrl } from '../config/env.js';
import { generateUuid, getClientIdentityHeaders } from '../config/headers.js';

// Load session manifest generated by scripts/load-test/setup.ts
let manifest = null;
try {
  manifest = JSON.parse(open('../.test-session.json'));
} catch {
  manifest = { users: [], clientHeaders: {} };
}

/**
 * Enterprise Multi-Module Stateful User Journey Benchmark
 *
 * Exercises 22 distinct endpoints across 9 core modules:
 *
 * Stage 0: One-Time Password Lifecycle (Ran on Iteration 0 per VU)
 *   - POST /api/v1/one-time-passwords/generate (Redis OTP issuance)
 *   - POST /api/v1/one-time-passwords/verify   (Redis single-use OTP consumption)
 *
 * Stage 1: Profiles & Cryptographic Identities
 *   - GET   /api/v1/profiles                  (Read profile)
 *   - PATCH /api/v1/profiles                  (Partial profile update)
 *   - GET   /api/v1/identities                (Masked identities)
 *   - GET   /api/v1/identities/complete       (KMS envelope decrypted identities)
 *
 * Stage 2: Preferences & GDPR Consent Audit Ledger
 *   - GET   /api/v1/preferences               (Notification channel toggles)
 *   - PATCH /api/v1/preferences               (Update preferences)
 *   - GET   /api/v1/preferences/consents      (GDPR consent audit trail)
 *
 * Stage 3: Credits & Ledger History
 *   - GET   /api/v1/credits/balance           (Spendable balance check)
 *   - GET   /api/v1/credits/expiring          (Expiring credit buckets)
 *   - GET   /api/v1/credits/ledger            (Paginated ledger / billing history)
 *
 * Stage 4: Subscriptions & Plans
 *   - GET   /api/v1/subscriptions/plans       (Localized active plans)
 *   - GET   /api/v1/subscriptions/me          (Active subscription check - 200 or 404)
 *   - GET   /api/v1/subscriptions/me/history  (Subscription purchase history)
 *
 * Stage 5: Blocks & Safety
 *   - GET   /api/v1/blocks                    (Active blocked users list)
 *
 * Stage 6: Notification Counters & Devices
 *   - GET   /api/v1/notifications/unread-count (Unread notification badge counter)
 *   - GET   /api/v1/devices                   (Registered client devices)
 *
 * Stage 7: Discovery, Likes & Reciprocal Match Resolver
 *   - GET   /api/v1/likes                     (Sent likes list)
 *   - POST  /api/v1/likes/can-create          (Pre-flight check before liking)
 *   - POST  /api/v1/likes                     (Send Like - reciprocal on Iter 0 triggers MatchResolver)
 *   - GET   /api/v1/matches                   (Active resolved matches)
 *   - GET   /api/v1/chats/rooms               (Active chat rooms spawned by matches)
 *   - GET   /api/v1/chats/supabase-token      (Supabase Realtime JWT token)
 */
export const options = {
  stages: [
    { duration: '15s', target: 5 }, // Warm up with 5 users
    { duration: '30s', target: 20 }, // Sustain 20 active concurrent users
    { duration: '15s', target: 0 }, // Clean ramp down
  ],
  thresholds: {
    http_req_duration: ['p(95)<2000', 'p(99)<3500'],
    http_req_failed: ['rate<0.05'],
  },
};

export default function () {
  const users = manifest.users;

  if (!users || users.length === 0) {
    throw new Error(
      '❌ No test session manifest found! Run "pnpm run test:load:setup" before running this test.',
    );
  }

  const baseUrl = getBaseUrl();
  const count = users.length;

  // Resolve current simulated user for this VU
  const userIndex = (__VU - 1) % count;
  const currentUser = users[userIndex];

  /**
   * Reciprocal Pairing Strategy:
   *
   * Iteration 0: Pair users reciprocally to trigger real MATCHES!
   *   - Even user i pairs with i + 1
   *   - Odd user i + 1 pairs with i
   *   -> Reciprocal likes trigger MatchResolverService to spawn real Matches and ChatRooms!
   *
   * Iteration 1+: Shift target cyclically across the remaining pool
   *   - Avoids repeatedly spamming the same target
   */
  let targetIndex;
  if (__ITER === 0) {
    targetIndex =
      userIndex % 2 === 0
        ? (userIndex + 1) % count
        : (userIndex - 1 + count) % count;
  } else {
    const shift = (__ITER % (count - 1)) + 1;
    targetIndex = (userIndex + shift) % count;
  }
  const targetUser = users[targetIndex];

  // Base client identity headers from manifest
  const clientIdentityConfig =
    manifest.clientHeaders && manifest.clientHeaders['x-api-key']
      ? manifest.clientHeaders
      : {};

  /**
   * Generates unique request headers per action:
   * - Unique x-request-id for distributed tracing.
   * - Dedicated virtual client IP per VU (198.51.100.X) for individual rate-limit tracking.
   * - Bearer JWT token from pre-seeded session.
   */
  function makeHeaders() {
    const virtualIp = `198.51.100.${__VU}`;
    return getClientIdentityHeaders({
      ...clientIdentityConfig,
      'x-request-id': generateUuid(),
      'x-forwarded-for': virtualIp,
      'x-real-ip': virtualIp,
      Authorization: `Bearer ${currentUser.token}`,
    });
  }

  // ==========================================
  // STAGE 0: ONE-TIME PASSWORDS (Iteration 0)
  // ==========================================
  if (__ITER === 0) {
    group('0. One-Time Password Flow', () => {
      const genRes = http.post(
        `${baseUrl}/api/v1/one-time-passwords/generate`,
        null,
        {
          headers: makeHeaders(),
          tags: { name: 'Flow_GenerateOtp' },
        },
      );

      const genOk = check(genRes, {
        'generate OTP returns 201': (r) => r.status === 201,
        'generate OTP returns otp token': (r) => {
          try {
            return !!r.json('otp');
          } catch {
            return false;
          }
        },
      });

      if (genOk) {
        const otpValue = genRes.json('otp');
        const verifyPayload = JSON.stringify({ otp: otpValue });

        const verifyRes = http.post(
          `${baseUrl}/api/v1/one-time-passwords/verify`,
          verifyPayload,
          {
            headers: makeHeaders(),
            tags: { name: 'Flow_VerifyOtp' },
          },
        );

        check(verifyRes, {
          'verify OTP returns 201': (r) => r.status === 201,
        });
      }
    });

    sleep(0.3);
  }

  // ==========================================
  // STAGE 1: PROFILES & IDENTITIES
  // ==========================================

  // 1. Fetch own profile
  group('1. Profile - Read', () => {
    const res = http.get(`${baseUrl}/api/v1/profiles`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetProfile' },
    });
    check(res, { 'get profile returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 2. Patch user profile
  group('2. Profile - Update', () => {
    const updatePayload = JSON.stringify({
      firstName: `LoadTest_VU${__VU}_U`,
    });
    const res = http.patch(`${baseUrl}/api/v1/profiles`, updatePayload, {
      headers: makeHeaders(),
      tags: { name: 'Flow_PatchProfile' },
    });
    check(res, { 'patch profile returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 3. Fetch masked identities
  group('3. Identities - Masked', () => {
    const res = http.get(`${baseUrl}/api/v1/identities`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetIdentities' },
    });
    check(res, { 'get identities returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 4. Fetch complete (decrypted) identities - tests KMS envelope decryption under load
  group('4. Identities - Complete (Decrypted)', () => {
    const res = http.get(`${baseUrl}/api/v1/identities/complete`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetIdentitiesComplete' },
    });
    check(res, {
      'get complete identities returns 200': (r) => r.status === 200,
    });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 2: PREFERENCES & CONSENTS
  // ==========================================

  // 5. Fetch notification preferences
  group('5. Preferences - Read', () => {
    const res = http.get(`${baseUrl}/api/v1/preferences`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetPreferences' },
    });
    check(res, { 'preferences returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 6. Update notification preferences
  group('6. Preferences - Update', () => {
    const prefPayload = JSON.stringify({
      pushEnabled: true,
      emailEnabled: true,
    });
    const res = http.patch(`${baseUrl}/api/v1/preferences`, prefPayload, {
      headers: makeHeaders(),
      tags: { name: 'Flow_PatchPreferences' },
    });
    check(res, { 'patch preferences returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 7. Check GDPR consent audit history
  group('7. Consent Ledger', () => {
    const res = http.get(`${baseUrl}/api/v1/preferences/consents`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetConsents' },
    });
    check(res, { 'consents returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 3: CREDITS & LEDGER HISTORY
  // ==========================================

  // 8. Check spendable credit balance
  group('8. Credit Balance', () => {
    const res = http.get(`${baseUrl}/api/v1/credits/balance`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetCreditBalance' },
    });
    check(res, { 'credit balance returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 9. Check expiring credits
  group('9. Expiring Credits', () => {
    const res = http.get(`${baseUrl}/api/v1/credits/expiring`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetExpiringCredits' },
    });
    check(res, { 'expiring credits returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 10. Check credit ledger transactions
  group('10. Credit Ledger History', () => {
    const res = http.get(`${baseUrl}/api/v1/credits/ledger?page=1&limit=10`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetCreditLedger' },
    });
    check(res, { 'credit ledger returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 4: SUBSCRIPTIONS & PLANS
  // ==========================================

  // 11. Browse active subscription plans
  group('11. Subscription Plans', () => {
    const res = http.get(`${baseUrl}/api/v1/subscriptions/plans`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetSubscriptionPlans' },
    });
    check(res, { 'subscription plans returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 12. Check active subscription status (200 if active, 404 if none)
  group('12. Active Subscription', () => {
    const res = http.get(`${baseUrl}/api/v1/subscriptions/me`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetActiveSubscription' },
    });
    check(res, {
      'active subscription returns 200 or 404': (r) =>
        r.status === 200 || r.status === 404,
    });
  });

  sleep(0.2);

  // 13. Check subscription billing history
  group('13. Subscription History', () => {
    const res = http.get(`${baseUrl}/api/v1/subscriptions/me/history`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetSubscriptionHistory' },
    });
    check(res, { 'subscription history returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 5: BLOCKS & SAFETY
  // ==========================================

  // 14. Fetch active blocked users list
  group('14. Blocks List', () => {
    const res = http.get(`${baseUrl}/api/v1/blocks`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetBlocks' },
    });
    check(res, { 'blocks returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 6: NOTIFICATIONS & DEVICES
  // ==========================================

  // 15. Check unread notification counter
  group('15. Unread Notifications Count', () => {
    const res = http.get(`${baseUrl}/api/v1/notifications/unread-count`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetUnreadCount' },
    });
    check(res, { 'unread count returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 16. Check registered devices
  group('16. Registered Devices', () => {
    const res = http.get(`${baseUrl}/api/v1/devices`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetDevices' },
    });
    check(res, { 'devices returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // ==========================================
  // STAGE 7: LIKES, RECIPROCAL MATCHES & CHATS
  // ==========================================

  // 17. Fetch sent likes
  group('17. Sent Likes', () => {
    const res = http.get(`${baseUrl}/api/v1/likes`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetLikes' },
    });
    check(res, { 'likes returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  const likePayload = JSON.stringify({
    targetIdentityId: targetUser.identityId,
    intent: 'RELATIONSHIP',
    notifyRecipientAnonymously: false,
  });

  // 18. Pre-flight check: Can like this target?
  let canCreateLike = false;
  group('18. Can Create Like', () => {
    const res = http.post(`${baseUrl}/api/v1/likes/can-create`, likePayload, {
      headers: makeHeaders(),
      tags: { name: 'Flow_CanCreateLike' },
    });

    if (res.status === 200) {
      canCreateLike = true;
    }

    check(res, {
      'can-create like returns 200 or 409': (r) =>
        r.status === 200 || r.status === 409,
    });
  });

  sleep(0.2);

  // 19. Send Like (only if pre-flight check allowed it, avoiding redundant duplicate errors)
  if (canCreateLike) {
    group('19. Send Like', () => {
      const res = http.post(`${baseUrl}/api/v1/likes`, likePayload, {
        headers: makeHeaders(),
        tags: { name: 'Flow_CreateLike' },
      });

      check(res, {
        'create like returns 201': (r) => r.status === 201,
      });
    });

    sleep(0.4);
  }

  // 20. Fetch active matches (tests matching engine queries and reciprocal resolution)
  group('20. Active Matches', () => {
    const res = http.get(`${baseUrl}/api/v1/matches`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetMatches' },
    });
    check(res, { 'matches returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 21. Check active chat rooms (tests chat rooms spawned by reciprocal matches)
  group('21. Chat Rooms', () => {
    const res = http.get(`${baseUrl}/api/v1/chats/rooms`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetChatRooms' },
    });
    check(res, { 'chat rooms returns 200': (r) => r.status === 200 });
  });

  sleep(0.2);

  // 22. Get Supabase Realtime Chat JWT
  group('22. Realtime Chat Token', () => {
    const res = http.get(`${baseUrl}/api/v1/chats/supabase-token`, {
      headers: makeHeaders(),
      tags: { name: 'Flow_GetChatToken' },
    });
    check(res, { 'chat token returns 200': (r) => r.status === 200 });
  });

  sleep(0.8); // Standard user think-time between full app sessions
}
