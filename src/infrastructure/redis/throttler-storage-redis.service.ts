import {
  Inject,
  Injectable,
  OnApplicationShutdown,
  Optional,
} from '@nestjs/common';
import { ThrottlerStorage, ThrottlerStorageService } from '@nestjs/throttler';
import Redis from 'ioredis';

import { serializeError } from '@common/utils/error.utils';
import { ContextualLogger, LoggerService } from '@core/logger';

import { REDIS_CLIENT } from './redis.constants';

export type ThrottlerStorageRecord = Awaited<
  ReturnType<ThrottlerStorage['increment']>
>;

const THROTTLER_INCREMENT_LUA_SCRIPT = `
-- KEYS[1]: hitsKey
-- KEYS[2]: blockKey
-- ARGV[1]: ttlMs
-- ARGV[2]: limit
-- ARGV[3]: blockDurationMs

-- 1. Check if user is currently blocked
local blockTtl = redis.call('PTTL', KEYS[2])
if blockTtl > 0 then
    local blockSec = math.max(0, math.ceil(blockTtl / 1000))
    return { tonumber(ARGV[2]) + 1, blockSec, 1, blockSec }
end

-- 2. Increment hit counter
local totalHits = redis.call('INCR', KEYS[1])
if totalHits == 1 then
    redis.call('PEXPIRE', KEYS[1], ARGV[1])
end

local pttlHits = redis.call('PTTL', KEYS[1])
if pttlHits < 0 then
    redis.call('PEXPIRE', KEYS[1], ARGV[1])
    pttlHits = tonumber(ARGV[1])
end

local timeToExpire = math.max(0, math.ceil(pttlHits / 1000))
local limit = tonumber(ARGV[2])
local blockDuration = tonumber(ARGV[3])

if totalHits > limit then
    local timeToBlockExpire = timeToExpire
    if blockDuration > 0 then
        redis.call('SET', KEYS[2], '1', 'PX', blockDuration)
        timeToBlockExpire = math.max(0, math.ceil(blockDuration / 1000))
    end
    return { totalHits, timeToExpire, 1, timeToBlockExpire }
else
    return { totalHits, timeToExpire, 0, 0 }
end
`;

/**
 * Resilient Redis-backed storage provider for `@nestjs/throttler`.
 *
 * Coordinates rate limiting hit counters and block durations globally across all
 * scaled Google Cloud Run container instances, eliminating in-memory counter isolation.
 * Automatically falls back to an in-memory `ThrottlerStorageService` if Redis is
 * unconfigured or temporarily unavailable.
 */
@Injectable()
export class ThrottlerStorageRedisService
  implements ThrottlerStorage, OnApplicationShutdown
{
  private readonly logger: ContextualLogger;
  private readonly fallbackStorage: ThrottlerStorageService;
  private readonly keyPrefix = 'throttle';

  constructor(
    @Optional()
    @Inject(REDIS_CLIENT)
    private readonly redisClient: Redis | null,
    loggerService: LoggerService,
  ) {
    this.logger = loggerService.forContext(ThrottlerStorageRedisService.name);
    this.fallbackStorage = new ThrottlerStorageService();
  }

  /**
   * Atomically increments the hit counter for the given tracker key, evaluating
   * window expirations and block durations via Redis Lua scripting.
   *
   * @param key - Unique request key generated by ThrottlerGuard.
   * @param ttl - Window duration in milliseconds.
   * @param limit - Max allowed hits within the window.
   * @param blockDuration - Lockout duration in milliseconds when limit is exceeded.
   * @param throttlerName - Named throttler bucket identifier (e.g. 'short', 'medium', 'long').
   */
  async increment(
    key: string,
    ttl: number,
    limit: number,
    blockDuration: number,
    throttlerName: string,
  ): Promise<ThrottlerStorageRecord> {
    if (!this.redisClient) {
      return this.fallbackStorage.increment(
        key,
        ttl,
        limit,
        blockDuration,
        throttlerName,
      );
    }

    try {
      return await this.incrementInRedis(
        key,
        ttl,
        limit,
        blockDuration,
        throttlerName,
      );
    } catch (error) {
      this.logger.warn(
        'Redis throttler increment failed; falling back to in-memory store',
        {
          key,
          throttlerName,
          step: 'redis_throttler_fallback',
          err: serializeError(error),
        },
      );
      return this.fallbackStorage.increment(
        key,
        ttl,
        limit,
        blockDuration,
        throttlerName,
      );
    }
  }

  private async incrementInRedis(
    key: string,
    ttl: number,
    limit: number,
    blockDuration: number,
    throttlerName: string,
  ): Promise<ThrottlerStorageRecord> {
    const hitsKey = `${this.keyPrefix}:${key}:${throttlerName}:hits`;
    const blockKey = `${this.keyPrefix}:${key}:${throttlerName}:blocked`;

    const result = (await this.redisClient!.eval(
      THROTTLER_INCREMENT_LUA_SCRIPT,
      2,
      hitsKey,
      blockKey,
      ttl,
      limit,
      blockDuration,
    )) as [number, number, number, number];

    return {
      totalHits: Number(result[0]),
      timeToExpire: Number(result[1]),
      isBlocked: Boolean(result[2]),
      timeToBlockExpire: Number(result[3]),
    };
  }

  /**
   * Cleans up fallback in-memory timers upon application termination.
   */
  onApplicationShutdown(): void {
    this.fallbackStorage.onApplicationShutdown();
  }
}
