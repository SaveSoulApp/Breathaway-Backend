/**
 * Canonical path constants for all Swagger UI endpoints.
 *
 * These are the single source of truth shared between:
 * - `swagger.config.ts`      → registers Swagger docs at these paths
 * - `swagger-basic-auth.config.ts` → guards these exact paths with Basic Auth
 *
 * A mismatch between registration and protection would silently expose the
 * API docs publicly, so both files MUST reference these constants.
 */
export const SWAGGER_PUBLIC_PATH = 'api/public' as const;
export const SWAGGER_ADMIN_PATH = 'api/admin' as const;
export const REDOC_SUBPATH = 'redoc' as const;
export const DOCS_PATH = 'docs' as const;

export const SWAGGER_PROTECTED_PATHS = [
  SWAGGER_PUBLIC_PATH,
  SWAGGER_ADMIN_PATH,
  DOCS_PATH,
] as const;

/**
 * Determines whether a given request path or URL corresponds to a documentation route
 * (Swagger UI, ReDoc, OpenAPI JSON specs, or Docusaurus static docs).
 *
 * Strips query parameters and hashes before matching against SWAGGER_PROTECTED_PATHS.
 *
 * @param urlOrPath - The incoming request URL or pathname.
 * @returns `true` if the URL matches a documentation route, otherwise `false`.
 */
export function isDocumentationPath(urlOrPath?: string | null): boolean {
  if (!urlOrPath) return false;
  const pathname = urlOrPath.split('?')[0].split('#')[0];
  return SWAGGER_PROTECTED_PATHS.some((path) => {
    if (pathname === `/${path}` || pathname.startsWith(`/${path}/`)) {
      return true;
    }
    // OpenAPI spec endpoints generated by NestJS Swagger (e.g. /api/public-json, /api/admin-yaml)
    if (
      (path === SWAGGER_PUBLIC_PATH || path === SWAGGER_ADMIN_PATH) &&
      (pathname === `/${path}-json` || pathname === `/${path}-yaml`)
    ) {
      return true;
    }
    return false;
  });
}
